let currentCategory = "education";

/* SHOW CATEGORY */
function showCategory(category) {
  currentCategory = category;
  displayItems(data[category]);
}

/* DISPLAY */
function displayItems(items) {
  const content = document.getElementById("content");
  content.innerHTML = "";

  items.forEach((item, index) => {

    let stars = "";
    for (let i = 1; i <= 5; i++) {
      stars += i <= item.rating
        ? '<i class="fas fa-star"></i>'
        : '<i class="far fa-star"></i>';
    }

    content.innerHTML += `
      <div class="card">
        <img src="${item.img}">
        <h3>${item.name}</h3>
        <p>${item.desc}</p>
        <p>📍 ${item.location}</p>
        <div class="stars">${stars}</div>
        <button onclick="showDetails(${index})">View Details</button>
      </div>
    `;
  });
}

/* SEARCH */
/* IMPROVED GLOBAL SEARCH */
function searchItems() {
  let value = document.getElementById("search").value.toLowerCase();
  let results = [];

  // 1. Loop through every category in the data object (education, restaurant, etc.)
  for (let category in data) {
    // 2. Filter the items in that specific category
    let filtered = data[category].filter(item =>
      item.name.toLowerCase().includes(value) || 
      item.desc.toLowerCase().includes(value)
    );
    
    // 3. Add the matches to our results list
    results = results.concat(filtered);
  }

  // 4. Display everything we found across all categories
  displayItems(results);
}

/* TOP RATED */
function showTopRated() {
  let top = data[currentCategory].filter(item => item.rating >= 4);
  displayItems(top);
}


/* MODAL */
function showDetails(index) {
  const item = data[currentCategory][index];

  document.getElementById("modal-body").innerHTML = `
    <h2>${item.name}</h2>
    <p>${item.desc}</p>
    <p>📍 ${item.location}</p>
    <p>${item.details}</p>
    <p>⭐ ${item.rating}</p>
    <p>💬 ${item.reviews.join("<br>")}</p>
  `;

  document.getElementById("modal").style.display = "block";
}

function closeModal() {

  document.getElementById("modal").style.display = "none";
}
